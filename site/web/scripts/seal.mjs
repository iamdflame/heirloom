// Generates the wax-seal monogram: src/lib/seal-paths.ts (used by <Seal/>), public/seal.svg and public/favicon.svg.
// A slightly irregular 10-lobe blob, a ring cut into it and a slab-serif "H" cut out of the centre.
import { writeFileSync } from 'node:fs';

const LOBES = 10;
const pts = [];
const N = 240;
for (let i = 0; i < N; i++) {
  const t = (i / N) * Math.PI * 2;
  // lobes plus a low-frequency wobble so it doesn't look machine-made
  const r = 46 + 2.2 * Math.cos(LOBES * t) + 1.1 * Math.sin(3 * t + 0.7) + 0.6 * Math.cos(5 * t + 1.9);
  pts.push([50 + r * Math.cos(t), 50 + r * Math.sin(t)]);
}
const f = (n) => n.toFixed(2);
const blob = 'M' + pts.map(([x, y]) => `${f(x)} ${f(y)}`).join('L') + 'Z';

// ring: annulus from r=33 to r=36 as an even-odd path
const circ = (r) => `M${50 - r} 50a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0Z`;
const ring = circ(36) + circ(33.2);

// serif H, cap height 32 (y 34..66)
const rect = (x, y, w, h) => `M${x} ${y}h${w}v${h}h${-w}Z`;
const H = [
  rect(36.5, 35.5, 5.6, 29), // left stem
  rect(57.9, 35.5, 5.6, 29), // right stem
  rect(40, 48.4, 20, 3.4), // bar
  rect(32.6, 34, 13.4, 2.4), // serifs
  rect(32.6, 63.6, 13.4, 2.4),
  rect(54, 34, 13.4, 2.4),
  rect(54, 63.6, 13.4, 2.4),
].join('');

writeFileSync(
  new URL('../src/lib/seal-paths.ts', import.meta.url),
  `// generated by scripts/seal.mjs\nexport const SEAL_BLOB = '${blob}';\nexport const SEAL_RING = '${ring}';\nexport const SEAL_H = '${H}';\n`,
);

const svg = (fill, extraStyle = '') => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">${extraStyle}
<mask id="m"><path d="${blob}" fill="#fff"/><path d="${ring}" fill="#000" fill-rule="evenodd"/><path d="${H}" fill="#000"/></mask>
<rect class="s" width="100" height="100" fill="${fill}" mask="url(#m)"/>
</svg>
`;
writeFileSync(new URL('../public/seal.svg', import.meta.url), svg('#C8463D'));
writeFileSync(
  new URL('../public/favicon.svg', import.meta.url),
  svg('#C8463D', '<style>@media (prefers-color-scheme: dark){.s{fill:#E5776C}}</style>'),
);
console.log('seal written');
